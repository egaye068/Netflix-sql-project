CREATE TABLE netflix (
		show_id	VARCHAR (20),
		type_1	VARCHAR (20),
		title	VARCHAR (200),
		director	VARCHAR (500),
		cast_1	VARCHAR (1000),
		country	 VARCHAR (200),
		date_added	VARCHAR (50),
		release_year	INT,
		rating	VARCHAR (20),
		duration	VARCHAR (20),
		listed_in	VARCHAR (200),
		description VARCHAR (500)
);

